export function translateText(value: string, language: Language): string {
  if (language === 'en') return value;
  if (PHRASES[value]) return PHRASES[value];

  // Exact phrase first, then transliterate individual English words while preserving
  // punctuation, spacing, numerals, item IDs and currency symbols.
  return value.replace(/[A-Za-z]+(?:[’'][A-Za-z]+)?/g, (word) => {
    const lower = word.toLowerCase();
    if (PHRASES[word]) return PHRASES[word];
    if (WORDS[lower]) return WORDS[lower];
    return word;
  });
}

export function translatedCategoryKey(value: string, language: Language): string {
  return translateText(value, language);
}
